// Run only against the synthetic .dsh-test-* bench used by companion-ui.mjs.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { readFileSync, mkdirSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'

const [packageRoot, logPath, port] = process.argv.slice(2)
if (!packageRoot || !logPath || !/^\d+$/.test(port ?? '') || !basename(dirname(resolve(logPath))).startsWith('.dsh-test-')) throw new Error('Expected an isolated .dsh-test-* bench')
const { chromium } = createRequire(join(resolve(packageRoot), 'package.json'))('playwright-core')
const login = readFileSync(logPath, 'utf8').match(new RegExp(`http://127\\.0\\.0\\.1:${port}/\\?token=[^\\s]+`))?.[0]
if (!login) throw new Error('The isolated bench has no login URL')
const out = dirname(resolve(logPath))
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}) })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const settle = () => page.waitForTimeout(500)
const options = () => page.getByRole('button', { name: '工作区视图选项', exact: true })
const chooseView = async label => { await options().click(); await page.getByRole('menuitemradio', { name: label, exact: true }).click(); await settle() }
const checkHidden = async owned => {
  const ids = await page.locator('.bt-ws-browser [data-session-id]').evaluateAll(nodes => nodes.map(node => node.dataset.sessionId))
  assert.ok(ids.every(id => !owned.has(id)), 'no Bot/private/group/worker/history row leaks into ordinary browsing')
}
const rowById = id => page.locator(`.bt-ws-browser [data-session-id="${id}"]`)
const rowMenu = async id => { const row = rowById(id); await row.hover(); await row.locator('.bt-ws-row-menu').click() }
try {
  await page.goto(login)
  const notice = page.getByRole('dialog').getByRole('button', { name: /^(继续|Continue)$/ })
  await page.addLocatorHandler(notice, () => notice.click())
  await page.locator('.bt-ws-row').first().waitFor({ timeout: 30000 })
  const readState = () => page.evaluate(() => fetch('api/bot', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ endpoint: 'state', payload: {} }) }).then(response => response.json()))
  let result = await readState()
  assert.equal(result.ok, true)
  if (!result.value.rooms.some(room => room.parts.length > 0)) {
    await page.getByRole('button', { name: '大肥鱼', exact: true }).first().click()
    await page.getByRole('button', { name: '切换伙伴', exact: true }).click()
    await page.locator(`[data-picker-choice="${result.value.rooms[0].id}"]`).click()
    await page.locator('[data-composer-input]').fill('群聊列表隔离验收')
    await page.locator('[data-composer-input]').press('Enter')
    await page.waitForFunction(async () => {
      const response = await fetch('api/bot', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ endpoint: 'state', payload: {} }) }).then(response => response.json())
      return response.value?.rooms.some(room => room.parts.length > 0)
    }, undefined, { timeout: 30000 })
    await page.waitForTimeout(1800)
    result = await readState()
  }
  const state = result.value
  const owned = new Set([...state.bots.flatMap(bot => [bot.id, bot.sessionId, ...bot.parts]), ...state.rooms.flatMap(room => [room.id, ...room.parts])])
  assert.ok(state.rooms.some(room => room.parts.length > 0), 'fixture includes group worker sessions')
  await checkHidden(owned)
  await chooseView('所有会话')
  await chooseView('显示已归档')
  await checkHidden(owned)
  await chooseView('按工作区分组')
  await chooseView('隐藏已归档')
  const first = page.locator('.bt-ws-row:not([data-blank])').first()
  const id = await first.getAttribute('data-session-id')
  const oldName = await first.locator('.bt-ws-copy>span').innerText()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: /^置顶$|^Pin$/ }).click()
  await settle()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: /^取消置顶$|^Unpin$/ }).click()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: /^重命名$|^Rename$/ }).click()
  const rename = page.getByRole('dialog')
  await rename.locator('input').fill(state.bots[0].name)
  await rename.getByRole('button', { name: /^重命名$|^Rename$/ }).click()
  await settle()
  assert.ok(await rowById(id).isVisible(), 'an ordinary conversation with the same name as a Bot is still visible')
  await page.getByRole('button', { name: '搜索会话', exact: true }).click()
  await page.getByRole('searchbox', { name: '搜索普通会话' }).fill(state.bots[0].name)
  await page.waitForTimeout(1100)
  await checkHidden(owned)
  assert.ok(await rowById(id).isVisible())
  await page.getByRole('searchbox', { name: '搜索普通会话' }).fill('你好，入口验收')
  await page.waitForTimeout(1100)
  await checkHidden(owned)
  assert.equal(await page.locator('.bt-ws-row').count(), 0, 'content-only Bot hits are hidden too')
  await page.getByRole('button', { name: '关闭搜索', exact: true }).click()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: /^重命名$|^Rename$/ }).click()
  await rename.locator('input').fill(oldName)
  await rename.getByRole('button', { name: /^重命名$|^Rename$/ }).click()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: '归档会话', exact: true }).click()
  await rowById(id).waitFor({ state: 'detached' })
  await chooseView('仅已归档')
  await checkHidden(owned)
  await rowMenu(id)
  await page.getByRole('menuitem', { name: '取消归档', exact: true }).click()
  await rowById(id).waitFor({ state: 'detached' })
  await chooseView('隐藏已归档')
  await rowById(id).waitFor()
  await rowById(id).locator('.bt-ws-session').click()
  await page.locator('[data-composer-input]').waitFor()
  assert.equal(await page.locator('.bt-head').count(), 0)
  console.log('PASS: owned rows hidden in grouped/flat/archive/content search; ordinary same-name chat, pin, rename, archive and restore work')

  await page.locator('[data-composer-input]').fill('慢慢说，归档确认验收')
  await page.locator('[data-composer-input]').press('Enter')
  await rowById(id).getByLabel('工作中', { exact: true }).waitFor()
  await rowMenu(id)
  await page.getByRole('menuitem', { name: '归档会话', exact: true }).click()
  const stopping = page.getByRole('dialog', { name: '停止并归档', exact: true })
  await stopping.waitFor()
  await stopping.getByRole('button', { name: '取消', exact: true }).click()
  assert.ok(await rowById(id).isVisible(), 'cancelling keeps the session unarchived')
  await rowMenu(id)
  await page.getByRole('menuitem', { name: '归档会话', exact: true }).click()
  await stopping.getByRole('button', { name: '停止并归档', exact: true }).click()
  await rowById(id).waitFor({ state: 'detached' })
  await chooseView('仅已归档')
  await rowMenu(id)
  await page.getByRole('menuitem', { name: '取消归档', exact: true }).click()
  await chooseView('隐藏已归档')
  console.log('PASS: active work is archived only after confirmation; cancelling preserves the session')

  const folder = join(out, 'ordinary-workspace')
  mkdirSync(folder, { recursive: true })
  await page.getByRole('button', { name: '添加工作区', exact: true }).click()
  const add = page.getByRole('dialog', { name: '添加工作区', exact: true })
  await add.getByRole('textbox', { name: '文件夹路径' }).fill(folder)
  await add.getByRole('button', { name: /浏览文件夹/ }).click()
  await add.getByRole('button', { name: /保存|Save/ }).click()
  await add.waitFor({ state: 'detached' })
  const group = page.locator('.bt-ws-group').filter({ has: page.locator('.bt-ws-folder-title', { hasText: 'ordinary-workspace' }) })
  await group.waitFor()
  await group.locator('.bt-ws-folder>.bt-ws-row-menu').click()
  await page.getByRole('menuitem', { name: '重命名工作区', exact: true }).click()
  await page.getByRole('dialog').locator('input').fill('Ordinary workspace UI check')
  await page.getByRole('dialog').getByRole('button', { name: /保存|Save/ }).click()
  const renamed = page.locator('.bt-ws-group').filter({ has: page.locator('.bt-ws-folder-title', { hasText: 'Ordinary workspace UI check' }) })
  await renamed.locator('.bt-ws-folder-title').click()
  assert.equal(await renamed.locator('.bt-ws-row').count(), 0)
  await renamed.locator('.bt-ws-folder-title').click()
  await renamed.locator('.bt-ws-folder>.bt-ws-row-menu').click()
  await page.getByRole('menuitem', { name: '移除工作区', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '移除工作区', exact: true }).click()
  await renamed.waitFor({ state: 'detached' })
  await chooseView('工作区目录树')
  await checkHidden(owned)
  await chooseView('按工作区分组')
  await page.screenshot({ path: join(out, 'ordinary-workspace-list.png') })
  await page.emulateMedia({ colorScheme: 'dark' })
  await settle()
  await page.screenshot({ path: join(out, 'ordinary-workspace-list-dark.png') })
  await page.setViewportSize({ width: 1024, height: 700 })
  await checkHidden(owned)
  console.log('PASS: workspace folder picker, add, rename, collapse, remove and view controls; light/dark/narrow screenshots')
  assert.deepEqual(errors, [])
} catch (error) {
  await page.screenshot({ path: join(out, 'workspace-failure.png') }).catch(() => {})
  throw error
} finally {
  await browser.close()
}
